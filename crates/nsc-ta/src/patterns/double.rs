//! Double and triple tops and bottoms.
//!
//! Two or three swings at a similar price with a pullback in between. How
//! similar counts as similar is measured against normal candle size.
//!
//! Note the overlap with `levels.rs`: a double top **is** a resistance zone
//! with two touches. This module exists to name the shape and add the neckline
//! trigger, not to duplicate the level. Where the two disagree, the level
//! wins.
