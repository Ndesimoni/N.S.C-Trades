//! Everything drawn on top of the candles.
//!
//! Levels, trendlines, the Fibonacci set with the move it measured marked, the
//! trigger candle highlighted, and the entry, stop and target lines with the
//! risk and reward areas shaded in.
//!
//! The Fibonacci **anchor** is drawn, not just the levels. When a Fibonacci
//! signal looks wrong to you, the argument is nearly always about which move
//! got measured — and showing it turns a vague "that looks off" into something
//! specific you can fix.
//!
//! Restraint matters. Every extra thing drawn is one more thing between you
//! and the price action. A chart with eleven annotations is harder to judge
//! than one with four.
