//! Fibonacci retracements and extensions over a move.
//!
//! The ratios are the easy part. **Which move you measure is the whole game.**
//! The same ratios drawn from a different swing pair give completely different
//! prices.
//!
//! So the move the bot measured is stored alongside the levels and shown in
//! the signal's reasoning. When a Fibonacci signal looks wrong to you, the
//! move it picked is almost always the disagreement.
//!
//! Which ratios count as the entry zone, the golden pocket, and the targets
//! are set in `config/ta.toml`.
